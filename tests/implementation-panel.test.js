/* ============================================================
   PART 2 — Implementation panel and generated docs

   Pins two things the owner asked for:
     - the panel renders from generated, evidence-based data (no hand-written
       claims), and the generator and the doc agree
     - the panel offers the shadcn-style primitives, filters, expandable rows
       and an Attribution section with real links
   ============================================================ */

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const root = path.join(__dirname, '..');
const read = rel => fs.readFileSync(path.join(root, rel), 'utf8');

// A minimal DOM good enough for the renderer: elements keyed by id, plus
// querySelectorAll over the mounted markup.
function makeDom() {
    const hosts = {};
    function makeEl(id) {
        const el = {
            id,
            innerHTML: '',
            textContent: '',
            _listeners: {},
            classList: { toggle() {}, add() {}, remove() {} },
            getAttribute() { return null; },
            addEventListener(type, fn) { (this._listeners[type] = this._listeners[type] || []).push(fn); },
            querySelectorAll() { return { forEach() {} }; }
        };
        return el;
    }
    for (const id of ['impl-content', 'impl-filters', 'impl-generated-at']) hosts[id] = makeEl(id);
    return {
        readyState: 'complete',
        getElementById: id => hosts[id] || null,
        addEventListener() {},
        _hosts: hosts
    };
}

function loadPanel(dom) {
    const src = read('src/devtools/implementation-data.js') + '\n' + read('src/devtools/implementation-panel.js');
    const sandbox = vm.createContext({ console, document: dom });
    vm.runInContext('var window = this; var globalThis = this;', sandbox);
    vm.runInContext(src, sandbox);
    return sandbox;
}

test('the generated dataset is real, evidence-based and complete', () => {
    const data = require(path.join(root, 'src/devtools/implementation-data.js'));
    assert.equal(data.generatedFrom, 'npm run docs:implementation');
    assert.ok(data.stages.length >= 6, 'the pipeline needs its stages');
    assert.ok(data.firstParty.length > 50, 'the first-party inventory should cover the bundles');

    // Every first-party entry points at a real file that is in the manifest.
    const bundles = JSON.parse(read('src/bundles.json'));
    const manifest = new Set(Object.values(bundles).flat());
    for (const item of data.firstParty) {
        assert.ok(fs.existsSync(path.join(root, item.file)), `${item.file} must exist`);
        assert.ok(manifest.has(item.file), `${item.file} must be in src/bundles.json`);
    }
    // Third-party versions are real package.json versions.
    const pkg = JSON.parse(read('package.json'));
    for (const dep of ['express', 'cors']) {
        const entry = data.thirdParty.find(t => t.name === dep);
        assert.ok(entry, `${dep} must be listed`);
        assert.equal(entry.version, pkg.dependencies[dep]);
    }
});

test('the generated markdown matches the dataset, so the doc cannot drift', () => {
    const data = require(path.join(root, 'src/devtools/implementation-data.js'));
    const md = read('docs/IMPLEMENTATION_COMPONENTS.md');
    assert.match(md, /Generated by `npm run docs:implementation`/);
    for (const stage of data.stages) {
        assert.ok(md.includes(stage.label), `doc must name the stage "${stage.label}"`);
    }
    for (const item of data.firstParty.slice(0, 10)) {
        assert.ok(md.includes(item.file), `doc must list ${item.file}`);
    }
    for (const item of data.thirdParty) {
        assert.ok(md.includes(item.name), `doc must list third-party ${item.name}`);
    }
    // The hand-written, unsourced sentence is gone.
    assert.doesNotMatch(md, /Core compiler pipeline/);
});

test('regenerating produces no diff (the generator is deterministic)', () => {
    const before = read('docs/IMPLEMENTATION_COMPONENTS.md');
    const beforeData = read('src/devtools/implementation-data.js');
    execFileSync(process.execPath, ['scripts/docs-implementation.js'], { cwd: root });
    assert.equal(read('docs/IMPLEMENTATION_COMPONENTS.md'), before, 'doc must be reproducible');
    assert.equal(read('src/devtools/implementation-data.js'), beforeData, 'data must be reproducible');
});

test('the panel renders cards, tables, badges, filters and expandable rows', () => {
    const dom = makeDom();
    const sandbox = loadPanel(dom);
    sandbox.PseudopyImplementationPanel.init();
    const html = dom._hosts['impl-content'].innerHTML;

    assert.match(html, /pp-card/, 'uses the card primitive');
    assert.match(html, /pp-table/, 'uses the table primitive');
    assert.match(html, /pp-badge/, 'uses the badge primitive');
    assert.match(html, /data-expandable="1"/, 'rows are expandable');
    assert.match(html, /Compiler pipeline stages/);
    assert.match(html, /First-party components/);
    assert.match(html, /Third-party components/);
    assert.match(html, /External &amp; platform components/);

    // Filter chips are rendered with the active one set.
    assert.match(dom._hosts['impl-filters'].innerHTML, /pp-chip/);
    assert.match(dom._hosts['impl-filters'].innerHTML, /is-active/);
});

test('the panel Attribution section links to the documents instead of naming them as text', () => {
    const src = read('src/devtools/implementation-panel.js');
    assert.match(src, /href="docs\/IMPLEMENTATION_COMPONENTS\.md"/, 'must link the components doc');
    assert.match(src, /href="docs\/COMPILER_PIPELINE\.md"/, 'must link the pipeline doc');
    assert.doesNotMatch(src, /See docs\/IMPLEMENTATION_COMPONENTS\.md, docs\/COMPILER_PIPELINE\.md/,
        'the old plain-text reference must be gone');
});

test('every component in the panel is classified, never left unattributed', () => {
    const data = require(path.join(root, 'src/devtools/implementation-data.js'));
    for (const item of data.firstParty) {
        assert.ok(['compiler', 'app', 'devtools', 'database'].includes(item.group), `${item.file} needs a group`);
    }
    for (const item of data.thirdParty) {
        assert.ok(item.kind && item.source, `${item.name} needs a role and a source`);
    }
    for (const item of data.external) {
        assert.ok(item.kind && item.source, `${item.name} needs a role and a source`);
    }
});

test('the panel module is registered in the devtools bundle and the docs script exists', () => {
    const bundles = JSON.parse(read('src/bundles.json'));
    assert.ok(bundles['devtools.js'].includes('src/devtools/implementation-data.js'));
    assert.ok(bundles['devtools.js'].includes('src/devtools/implementation-panel.js'));
    // data must load before the renderer
    assert.ok(bundles['devtools.js'].indexOf('src/devtools/implementation-data.js') <
        bundles['devtools.js'].indexOf('src/devtools/implementation-panel.js'));

    const pkg = JSON.parse(read('package.json'));
    assert.equal(pkg.scripts['docs:implementation'], 'node scripts/docs-implementation.js');
});

test('the pipeline stage vocabulary is defined once and the doc references it', () => {
    const generator = read('scripts/docs-implementation.js');
    assert.match(generator, /const STAGES = \[/, 'stages come from the generator');
    const data = require(path.join(root, 'src/devtools/implementation-data.js'));
    const labels = data.stages.map(s => s.label);
    assert.equal(new Set(labels).size, labels.length, 'stage labels must be unique');
});

test('the thesis claim audit is present, honest and rendered', () => {
    const data = require(path.join(root, 'src/devtools/implementation-data.js'));
    assert.ok(Array.isArray(data.thesisClaims) && data.thesisClaims.length >= 3, 'claims must be audited');
    for (const c of data.thesisClaims) {
        assert.ok(['Verified', 'Qualified'].includes(c.status), `${c.claim}: unexpected status ${c.status}`);
        assert.ok(c.evidence && c.evidence.length > 20, `${c.claim}: needs real evidence`);
    }
    // The unqualified "no backend server needed" claim must be Qualified, since
    // server.js and api/ exist.
    const backend = data.thesisClaims.find(c => /backend server/i.test(c.claim));
    assert.equal(backend.status, 'Qualified');
    // And the doc states the same statuses.
    const md = read('docs/IMPLEMENTATION_COMPONENTS.md');
    assert.match(md, /## Thesis claim audit/);
    assert.match(md, /\| Claim \| Status \| Evidence \|/);

    // It appears in the rendered panel too.
    const dom = makeDom();
    const sandbox = loadPanel(dom);
    sandbox.PseudopyImplementationPanel.init();
    assert.match(dom._hosts['impl-content'].innerHTML, /Thesis claim audit/);
});
