/* ============================================================
   PART 3 — Panel compliance matrix

   The compliance matrix is only honest if:
     - every row cites a test name that actually exists in the suite, and
     - the cited test actually passes when run.

   This test enforces both, so a status can never be upgraded by editing a
   sentence. It reads the generated dataset, checks each named test is present
   in tests/*.test.js, runs the ones it can resolve, and asserts the matrix in
   docs/PANEL_COMPLIANCE.md matches the dataset.
   ============================================================ */

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const read = rel => fs.readFileSync(path.join(root, rel), 'utf8');

const data = require(path.join(root, 'src/devtools/implementation-data.js'));

function allTestSource() {
    const dir = path.join(root, 'tests');
    return fs.readdirSync(dir)
        .filter(f => f.endsWith('.test.js'))
        .map(f => read(path.join('tests', f)))
        .join('\n');
}

test('every compliance row cites a test that exists in the suite', () => {
    const suite = allTestSource();
    for (const row of data.compliance) {
        assert.ok(row.test, `${row.id} must name a test`);
        // The cited name must appear as a literal test title in the suite.
        assert.ok(suite.includes(row.test), `${row.id} cites a test that does not exist: "${row.test}"`);
    }
});

test('a row may only be Complete when it carries no remaining gap', () => {
    for (const row of data.compliance) {
        if (row.status === 'Complete') {
            assert.equal(row.gap, null, `${row.id} is Complete but still lists a gap`);
            assert.equal(row.ownerAction, null, `${row.id} is Complete but still lists an owner action`);
        } else {
            assert.ok(row.gap, `${row.id} is ${row.status} and must state the gap`);
            assert.ok(row.ownerAction, `${row.id} is ${row.status} and must state an owner action`);
        }
    }
});

test('the panel comments are all represented (C1 through C5)', () => {
    const ids = data.compliance.map(c => c.id);
    for (const id of ['C1', 'C2', 'C3', 'C4', 'C5']) {
        assert.ok(ids.includes(id), `comment ${id} must be in the matrix`);
    }
});

test('the generated PANEL_COMPLIANCE.md matches the dataset it claims to render', () => {
    const md = read('docs/PANEL_COMPLIANCE.md');
    assert.match(md, /Generated by `npm run docs:implementation`/);
    for (const row of data.compliance) {
        assert.ok(md.includes(row.id), `doc must include ${row.id}`);
        assert.ok(md.includes(`**${row.status}**`), `doc must show ${row.id} as ${row.status}`);
    }
    // Every Partial/Missing row's owner action is written down.
    for (const row of data.compliance.filter(r => r.status !== 'Complete')) {
        assert.ok(md.includes(row.ownerAction), `doc must record the owner action for ${row.id}`);
    }
});

test('the named verification tests actually pass when run', () => {
    // Resolve each cited title to its file, then run that file. The cited test
    // must appear in the passing output. This is the "run the system, do not
    // read the claim" requirement.
    const files = fs.readdirSync(path.join(root, 'tests')).filter(f => f.endsWith('.test.js'));
    for (const row of data.compliance) {
        const file = files.find(f => read(path.join('tests', f)).includes(row.test));
        assert.ok(file, `${row.id}: no test file contains "${row.test}"`);
        // node --test exits non-zero when any test in the file fails, so capture
        // the output regardless of exit status and judge it from the TAP text.
        // NODE_TEST_CONTEXT is cleared so the child prints its own TAP summary
        // instead of deferring to the parent reporter.
        const env = { ...process.env, PYTHON: process.env.PYTHON || 'python' };
        delete env.NODE_TEST_CONTEXT;
        const run = require('node:child_process').spawnSync(
            process.execPath,
            ['--test', '--test-reporter=tap', path.join('tests', file)],
            { cwd: root, encoding: 'utf8', env }
        );
        const out = (run.stdout || '') + (run.stderr || '');
        assert.doesNotMatch(out, /^\s*not ok \d+/m, `${row.id}: ${file} has failing tests`);
        const passMatch = out.match(/# pass (\d+)/);
        assert.ok(passMatch && Number(passMatch[1]) > 0, `${row.id}: ${file} reported no passes`);
    }
});

test('the compliance card is rendered in the panel', () => {
    const panel = read('src/devtools/implementation-panel.js');
    assert.match(panel, /function complianceCard/);
    assert.match(panel, /Panel comments/);
    assert.match(panel, /docs\/PANEL_COMPLIANCE\.md/);
    const generator = read('scripts/docs-implementation.js');
    assert.match(generator, /const COMPLIANCE = \[/);
});
